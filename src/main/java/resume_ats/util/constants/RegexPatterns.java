package resume_ats.util.constants;

public final class RegexPatterns {

    private RegexPatterns() {
    }

    // =========================================================
    // EMAIL
    // =========================================================

    public static final String EMAIL = "[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}";

    // =========================================================
    // PHONE
    // =========================================================

    public static final String PHONE = "(\\+\\d{1,3}[\\s-]?)?(\\(?\\d{2,5}\\)?[\\s-]?)?\\d{10}";

    // =========================================================
    // EXPERIENCE
    // =========================================================

    public static final String EXPERIENCE = "(\\d+(\\.\\d+)?)\\s*(\\+)?\\s*(year|years|yr|yrs|month|months|mo)";

    // =========================================================
    // LINKEDIN
    // =========================================================

    public static final String LINKEDIN = "(https?:\\/\\/)?(www\\.)?linkedin\\.com\\/[A-Za-z0-9_\\-/?=&.%]+";

    // =========================================================
    // GITHUB
    // =========================================================

    public static final String GITHUB = "(https?:\\/\\/)?(www\\.)?github\\.com\\/[A-Za-z0-9_\\-]+";

    // =========================================================
    // PORTFOLIO WEBSITE
    // =========================================================

    public static final String WEBSITE = "(https?:\\/\\/)?([A-Za-z0-9\\-]+\\.)+[A-Za-z]{2,}(/[A-Za-z0-9_\\-./?=&%]*)?";

    // =========================================================
    // DATE
    // =========================================================

    public static final String DATE = "\\b\\d{1,2}[/-]\\d{1,2}[/-]\\d{2,4}\\b";

    // =========================================================
    // YEAR
    // =========================================================

    public static final String YEAR = "\\b(19|20)\\d{2}\\b";

    // =========================================================
    // CGPA
    // =========================================================

    public static final String CGPA = "\\b\\d\\.\\d{1,2}\\b";

    // =========================================================
    // PERCENTAGE
    // =========================================================

    public static final String PERCENTAGE = "\\b\\d{1,3}(\\.\\d+)?\\s*%";

    // =========================================================
    // ZIP CODE / PINCODE
    // =========================================================

    public static final String PINCODE = "\\b\\d{6}\\b";

    // =========================================================
    // CURRENCY
    // =========================================================

    public static final String SALARY = "(₹|Rs\\.?|INR|\\$|USD)?\\s?\\d+(,\\d{3})*(\\.\\d+)?";

    // =========================================================
    // EMPLOYMENT TYPE
    // =========================================================

    public static final String EMPLOYMENT_TYPE = "(full time|part time|internship|contract|temporary|permanent|hybrid|remote|work from home)";

    // =========================================================
    // NAME
    // =========================================================

    public static final String NAME = "^[A-Z][a-zA-Z]+(?:\\s+[A-Z][a-zA-Z]+){1,3}$";

}